import type { Metadata } from "next";

/**
 * Службовий розділ `/guides/*` — інструкції, які ми надсилаємо клієнту
 * прямим посиланням.
 *
 * Закритий від індексації на рівні розділу, щоб нова сторінка не могла
 * випадково потрапити у видачу через забутий `robots`. Кожна сторінка
 * дублює це у своїй метадаті — Next зливає метадані, і дубль тут дешевий
 * страховий поліс, а не зайвий код.
 *
 * У robots.txt розділ НЕ закривається свідомо: заборона обходу завадила б
 * Google прочитати сам `noindex`, і сторінка могла б лишитись у видачі без
 * опису. Правильний порядок — дозволити обхід і віддати мета-тег.
 */
export const metadata: Metadata = {
  robots: { index: false, follow: false },
};

export default function GuidesLayout({
  children,
}: {
  children: React.ReactNode;
}) {
  return <>{children}</>;
}
